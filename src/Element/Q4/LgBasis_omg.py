import numpy as np
def LgBasis_omg(p, n):
    x = p[0]
    y = p[1]




    if n == 4:
        s = np.zeros(4)
        d = np.zeros((4, 4))
        s[3] = 0
        d[1, 3] = 0

        s[0] = 0.25 * [1 - x] * [1 - y]
        s[1] = 0.25 * [1 + x] * [1 - y]
        s[2] = 0.25 * [1 + x] * [1 + y]
        s[3] = 0.25 * [1 - x] * [1 + y]

        d[0, 0] = 0.25 * y - 0.25
        d[0, 1] = 0.25 - 0.25 * y
        d[0, 2] = 0.25 + 0.25 * y
        d[0, 3] = -0.25 - 0.25 * y

        d[1, 0] = 0.25 * x - 0.25
        d[1, 1] = -0.25 - 0.25 * x
        d[1, 2] = 0.25 + 0.25 * x
        d[1, 3] = 0.25 - 0.25 * x

    elif n == 8:
        s = np.zeros(8)
        d = np.zeros((8, 8))

        s[8] = 0
        d[2, 8] = 0

        s[0] = 0.25 * (x - 1) * (1 - y) * (1 + y + x)
        s[1] = 0.25 * (1 + x) * (1 - y) * (x - y - 1)
        s[2] = 0.25 * (1 + x) * (1 + y) * (y + x - 1)
        s[3] = 0.25 * (1 - x) * (1 + y) * (y - 1 - x)
        s[4] = 0.50 * (1 - x) * (1 + x) * (1 - y)
        s[5] = 0.50 * (1 - y) * (1 + y) * (1 + x)
        s[6] = 0.50 * (1 - x) * (1 + x) * (1 + y)
        s[7] = 0.50 * (1 - y) * (1 + y) * (1 - x)

        d[0, 0] = 0.25 * (1 - y) * (y + 2 * x)
        d[0, 1] = 0.25 * (1 - y) * (2 * x - y)
        d[0, 2] = 0.25 * (1 + y) * (y + 2 * x)
        d[0, 3] = 0.25 * (1 + y) * (2 * x - y)
        d[0, 4] = 1.00 * x * (y - 1)
        d[0, 5] = 0.50 * (1 - y) * (1 + y)
        d[0, 6] = -1.00 * x * (1 + y)
        d[0, 7] = 0.50 * (y - 1) * (1 + y)

        d[1, 0] = 0.25 * (1 - x) * (x + 2 * y)
        d[1, 1] = 0.25 * (1 + x) * (2 * y - x)
        d[1, 2] = 0.25 * (1 + x) * (x + 2 * y)
        d[1, 3] = 0.25 * (1 - x) * (2 * y - x)
        d[1, 4] = 0.50 * (x - 1) * (1 + x)
        d[1, 5] = -1.00 * y * (1 + x)
        d[1, 6] = 0.50 * (1 - x) * (1 + x)
        d[1, 7] = 1.00 * y * (x - 1)
    else:
        ImportError("n = ?")

    return s, d
